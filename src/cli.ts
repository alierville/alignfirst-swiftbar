import { execFileSync } from "node:child_process";
import {
  chmodSync,
  existsSync,
  lstatSync,
  mkdirSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { homedir } from "node:os";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { runAction } from "./actions.ts";
import { renderCheck } from "./check.ts";
import { collectProject, toPublic } from "./collect.ts";
import { checkConfig, PROJECT_FILE } from "./project-config.ts";
import { readRegistry, registryDir } from "./registry.ts";
import { initialProjectFile } from "./scaffold.ts";
import { addProject, readProjects, removeProject, storeDir } from "./store.ts";
import { renderSwiftBar } from "./swiftbar.ts";
import { isIgnoredByGit, listeningPorts, mainWorktreeOf } from "./system.ts";
import { slug } from "./text.ts";
import type { Snapshot } from "./types.ts";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const PLUGIN_PREFIX = "workspace-bar.";
const DEFAULT_INTERVAL = "10s";

const USAGE = `workspace-bar — AlignFirst workspace endpoints in the menu bar

  add <folder>           follow the repository containing this folder
  remove <key|folder>    stop following it
  list                   followed repositories
  init <folder>          create ${PROJECT_FILE} in the main worktree, from its AlignFirst ports
  check <folder>         show the menu a repository gets, and the errors in its project file
  json                   full state as JSON (without any secret)
  swiftbar               menu in SwiftBar format
  install [folder] [--every 5m]
                         install the SwiftBar plugin, refreshed at this interval (30s, 5m, 1h…)
`;

function fail(text: string): never {
  process.stderr.write(`workspace-bar: ${text}\n`);
  process.exit(1);
}

function snapshot(): Snapshot {
  const listening = listeningPorts();
  const projects = readProjects().map(collectProject);
  return {
    generatedAt: new Date().toISOString(),
    projects: projects.map((project) => toPublic(project, listening)),
  };
}

function resolveMain(dir: string | undefined): string {
  if (!dir) fail("missing folder");
  try {
    return mainWorktreeOf(resolve(dir));
  } catch {
    fail(`not a git repository: ${dir}`);
  }
}

function open(projectKey: string, worktreeKey: string, endpointId: string): void {
  const entry = readProjects().find((project) => project.key === projectKey);
  if (!entry) fail(`unknown project: ${projectKey}`);
  const project = collectProject(entry);
  const endpoint = project.worktrees
    .find((worktree) => worktree.key === worktreeKey)
    ?.endpoints.find((candidate) => candidate.id === endpointId);
  if (!endpoint) fail(`endpoint not found: ${worktreeKey}/${endpointId}`);
  if (!endpoint.action) fail(`${endpoint.label} : ${endpoint.unavailable ?? "unavailable"}`);
  runAction(endpoint.action);
}

function swiftBarPluginDirectory(): string {
  try {
    return execFileSync("/usr/bin/defaults", ["read", "com.ameba.SwiftBar", "PluginDirectory"], {
      encoding: "utf8",
    }).trim();
  } catch {
    fail(
      "unknown SwiftBar plugin folder: start SwiftBar once and choose it, or pass it as an argument",
    );
  }
}

function shellQuote(value: string): string {
  return `'${value.replaceAll("'", "'\\''")}'`;
}

function writeExecutable(path: string, content: string): void {
  writeFileSync(path, content, { mode: 0o700 });
  chmodSync(path, 0o700);
}

/**
 * Two files: a launcher in the user's config folder (a path without spaces, which SwiftBar calls
 * back on click) and the plugin in the SwiftBar folder, which only calls the launcher.
 */
function install(dir: string | undefined, interval: string): void {
  if (!/^[1-9][0-9]*[smhd]$/.test(interval))
    fail(`invalid interval: ${interval} (e.g. 30s, 5m, 1h)`);
  const target = resolve(dir ?? swiftBarPluginDirectory());
  // SwiftBar keeps each plugin's data there, as folders it would then try to load as plugins.
  if (target.startsWith(join(homedir(), "Library", "Application Support", "SwiftBar"))) {
    fail("SwiftBar data folder: choose a separate plugin folder (e.g. ~/.config/swiftbar-plugins)");
  }
  mkdirSync(target, { recursive: true });
  mkdirSync(storeDir(), { recursive: true, mode: 0o700 });
  const launcher = join(storeDir(), "workspace-bar");
  if (/[\s"]/.test(launcher)) fail(`unsupported launcher path: ${launcher}`);
  writeExecutable(
    launcher,
    `#!/bin/sh
# Generated by workspace-bar install: ${ROOT}
WORKSPACE_BAR_PLUGIN=${shellQuote(launcher)} exec ${shellQuote(process.execPath)} --disable-warning=ExperimentalWarning ${shellQuote(join(ROOT, "src", "cli.ts"))} "$@"
`,
  );
  // SwiftBar reads the refresh interval from the file name: drop a plugin installed with another one.
  for (const name of readdirSync(target)) {
    if (name.startsWith(PLUGIN_PREFIX) && name.endsWith(".sh")) rmSync(join(target, name));
  }
  const plugin = join(target, `${PLUGIN_PREFIX}${interval}.sh`);
  writeExecutable(
    plugin,
    `#!/bin/sh
# <xbar.title>Workspace Bar</xbar.title>
# <xbar.desc>AlignFirst workspace endpoints</xbar.desc>
# <swiftbar.hideAbout>true</swiftbar.hideAbout>
# <swiftbar.hideRunInTerminal>true</swiftbar.hideRunInTerminal>
# <swiftbar.hideLastUpdated>true</swiftbar.hideLastUpdated>
# <swiftbar.hideDisablePlugin>true</swiftbar.hideDisablePlugin>
exec ${shellQuote(launcher)} swiftbar
`,
  );
  process.stdout.write(`launcher: ${launcher}\nplugin:   ${plugin}\n`);
}

function init(dir: string | undefined): void {
  const main = resolveMain(dir);
  const path = join(main, PROJECT_FILE);
  if (existsSync(path)) fail(`already exists: ${path}`);
  mkdirSync(join(main, ".local"), { recursive: true, mode: 0o700 });
  if (!isIgnoredByGit(main, PROJECT_FILE))
    fail(`${PROJECT_FILE} is not ignored by git in ${main}: add .local/ to .gitignore`);
  if (lstatSync(join(main, ".local")).mode & 0o022)
    fail(`${join(main, ".local")} is writable by others: chmod go-w`);
  const portNames = registryPortNames(main);
  const file = initialProjectFile(basename(main), portNames);
  checkConfig(file);
  writeFileSync(path, `${JSON.stringify(file, null, 2)}\n`, { mode: 0o600 });
  process.stdout.write(`created: ${path}\n`);
  if (portNames.length === 0) {
    process.stdout.write(
      "no AlignFirst ports yet (npx alignfirst dev setup): add your entries by hand\n",
    );
  }
}

/** Every port name the registry knows, main worktree's first; none without a registry. */
function registryPortNames(main: string): string[] {
  try {
    const workspaces = readRegistry(main).workspaces.sort(
      (a, b) => Number(b.main) - Number(a.main),
    );
    return [...new Set(workspaces.flatMap((workspace) => Object.keys(workspace.ports)))];
  } catch {
    return [];
  }
}

function check(dir: string | undefined): void {
  const main = resolveMain(dir);
  const project = collectProject({ key: slug(basename(main)), path: main });
  const file = join(main, PROJECT_FILE);
  const report = renderCheck(toPublic(project, listeningPorts()), existsSync(file) ? file : null);
  process.stdout.write(report.text);
  if (!report.ok) process.exit(1);
}

async function main(args: string[]): Promise<void> {
  const [command, ...rest] = args;
  switch (command) {
    case "add": {
      const path = resolveMain(rest[0]);
      if (!existsSync(registryDir(path)))
        process.stderr.write("warning: no AlignFirst registry yet\n");
      const entry = addProject(path);
      process.stdout.write(`following: ${entry.key} → ${entry.path}\n`);
      return;
    }
    case "remove": {
      if (!rest[0]) fail("missing key or folder");
      const removed = removeProject(rest[0]) ?? removeProject(resolve(rest[0]));
      if (!removed) fail(`not followed: ${rest[0]}`);
      process.stdout.write(`removed: ${removed.key}\n`);
      return;
    }
    case "list":
      for (const entry of readProjects()) process.stdout.write(`${entry.key}\t${entry.path}\n`);
      return;
    case "init":
      return init(rest[0]);
    case "check":
      return check(rest[0]);
    case "json":
      process.stdout.write(`${JSON.stringify(snapshot(), null, 2)}\n`);
      return;
    case "swiftbar": {
      const plugin = process.env.WORKSPACE_BAR_PLUGIN;
      if (!plugin)
        fail("to be run by the SwiftBar plugin (see install), or with WORKSPACE_BAR_PLUGIN");
      process.stdout.write(renderSwiftBar(snapshot().projects, plugin));
      return;
    }
    case "open":
      if (rest.length !== 3) fail("usage: open <project> <worktree> <endpoint>");
      return open(rest[0], rest[1], rest[2]);
    case "install": {
      const at = rest.indexOf("--every");
      const interval = at >= 0 ? rest[at + 1] : DEFAULT_INTERVAL;
      if (at >= 0) rest.splice(at, 2);
      // An option is never a folder: `install --help` must not install the plugin into "./--help".
      const option = rest.find((arg) => arg.startsWith("-"));
      if (option) fail(`unknown option: ${option} (usage: install [folder] [--every 5m])`);
      if (rest.length > 1) fail("usage: install [folder] [--every 5m]");
      return install(rest[0], interval ?? "");
    }
    default:
      process.stdout.write(USAGE);
      if (command && command !== "help" && command !== "--help") process.exit(1);
  }
}

await main(process.argv.slice(2));
